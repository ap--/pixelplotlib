_ALIASES = {
    "\u2212": "-",  # minus sign
    "\u2013": "-",
    "\u2014": "-",
    "\u2018": "'",
    "\u2019": "'",
    "\u201c": '"',
    "\u201d": '"',
    "\u00b5": "μ",  # micro sign -> greek mu
    "\u2126": "Ω",
    "\u2206": "Δ",
    "\u2211": "Σ",
}


class BitmapFont:
    """A proportional bitmap font.

    Parameters
    ----------
    name:
        Font name.
    glyphs:
        Mapping of characters to glyph specs (see module docstring).
    ascent, descent:
        Rows above (and including) the baseline and below it.
    spacing:
        Blank columns between glyphs.
    line_gap:
        Blank rows between lines of multi-line text.
    uppercase:
        Render lowercase letters with their uppercase glyphs.
    """

    def __init__(
        self,
        name: str,
        glyphs: dict[str, str],
        ascent: int,
        descent: int = 0,
        spacing: int = 1,
        line_gap: int = 1,
        uppercase: bool = False,
    ):
        self.name = name
        self.ascent = ascent
        self.descent = descent
        self.spacing = spacing
        self.line_gap = line_gap
        self.uppercase = uppercase
        self._glyphs: dict[str, np.ndarray] = {}
        for ch, spec in glyphs.items():
            rows = spec.split()
            width = len(rows[0])
            if any(len(r) != width for r in rows) or len(rows) not in (ascent, ascent + descent):
                raise ValueError(f"malformed glyph {ch!r} in font {name!r}")
            bitmap = np.zeros((ascent + descent, width), dtype=bool)
            bitmap[: len(rows)] = np.array([[c == "#" for c in r] for r in rows], dtype=bool)
            self._glyphs[ch] = bitmap

    @property
    def line_height(self) -> int:
        return self.ascent + self.descent

    def __contains__(self, ch: str) -> bool:
        return self._resolve(ch) != "\ufffd" or ch == "\ufffd"

    def _resolve(self, ch: str) -> str:
        ch = _ALIASES.get(ch, ch)
        if self.uppercase and ch not in self._glyphs:
            ch = ch.upper()
        return ch if ch in self._glyphs else "\ufffd"

    def glyph(self, ch: str) -> np.ndarray:
        return self._glyphs[self._resolve(ch)]

    def measure(self, text: str) -> tuple[int, int]:
        """Return ``(width, height)`` in pixels of rendered ``text``."""
        lines = str(text).split("\n")
        width = max(self._line_width(line) for line in lines)
        height = len(lines) * self.line_height + (len(lines) - 1) * self.line_gap
        return width, height

    def _line_width(self, line: str) -> int:
        if not line:
            return 0
        return sum(self.glyph(c).shape[1] for c in line) + self.spacing * (len(line) - 1)

    def render(self, text: str, align: str = "left") -> np.ndarray:
        """Render ``text`` to a boolean mask of shape ``(height, width)``."""
        return _render_cached(self, str(text), align).copy()


@lru_cache(maxsize=4096)
def _render_cached(font: BitmapFont, text: str, align: str) -> np.ndarray:
    lines = text.split("\n")
    w, h = font.measure(text)
    out = np.zeros((h, w), dtype=bool)
    y = 0
    for line in lines:
        lw = font._line_width(line)
        x = {"left": 0, "center": (w - lw) // 2, "right": w - lw}[align]
        for ch in line:
            g = font.glyph(ch)
            out[y : y + g.shape[0], x : x + g.shape[1]] |= g
            x += g.shape[1] + font.spacing
        y += font.line_height + font.line_gap
    return out


FONT_5X7 = BitmapFont("5x7", _GLYPHS_5X7, ascent=7, descent=2)
FONT_3X5 = BitmapFont("3x5", _GLYPHS_3X5, ascent=5, descent=0, uppercase=True)

FONTS: dict[str, BitmapFont] = {"5x7": FONT_5X7, "3x5": FONT_3X5, "tiny": FONT_3X5}


def get_font(font: str | BitmapFont) -> BitmapFont:
    if isinstance(font, BitmapFont):
        return font
    try:
        return FONTS[font]
    except KeyError:
        raise ValueError(f"unknown font {font!r}; choose from {sorted(FONTS)}") from None
